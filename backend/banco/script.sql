CREATE TABLE PACIENTE (
    ID_PACIENTE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    CPF VARCHAR2(14),
    RG VARCHAR2(20),
    ENDERECO VARCHAR2(200),
    TELEFONE VARCHAR2(20),
    EMAIL VARCHAR2(100),
    GENERO VARCHAR2(20),
    DATA_NASCIMENTO DATE,

    CONSTRAINT PK_PACIENTE PRIMARY KEY (ID_PACIENTE)
);

CREATE TABLE PROFISSIONAL (
    ID_PROFISSIONAL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    REGISTRO_PROFISSIONAL VARCHAR2(30),
    TIPO_FUNCAO VARCHAR2(20) NOT NULL,
    ESPECIALIDADE VARCHAR2(100),

    CONSTRAINT PK_PROFISSIONAL PRIMARY KEY (ID_PROFISSIONAL),

    CONSTRAINT UK_PROFISSIONAL_EMAIL UNIQUE (EMAIL),

    CONSTRAINT CK_PROFISSIONAL_FUNCAO
        CHECK (TIPO_FUNCAO IN (
            'RECEPCIONISTA',
            'MEDICO',
            'ENFERMEIRO'
        ))
);

CREATE TABLE ATENDIMENTO (
    ID_ATENDIMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PACIENTE NUMBER NOT NULL,
    ID_PROFISSIONAL NUMBER NOT NULL,
    DATA_ATENDIMENTO DATE NOT NULL,
    HORA_INICIO VARCHAR2(5),
    HORA_FIM VARCHAR2(5),
    STATUS VARCHAR2(20) DEFAULT 'Agendado' NOT NULL,

    CONSTRAINT PK_ATENDIMENTO PRIMARY KEY (ID_ATENDIMENTO),

    CONSTRAINT FK_ATENDIMENTO_PACIENTE
        FOREIGN KEY (ID_PACIENTE)
        REFERENCES PACIENTE (ID_PACIENTE),

    CONSTRAINT FK_ATENDIMENTO_PROFISSIONAL
        FOREIGN KEY (ID_PROFISSIONAL)
        REFERENCES PROFISSIONAL (ID_PROFISSIONAL)
);

