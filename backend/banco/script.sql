CREATE TABLE PRONTUARIO (
    ID_PRONTUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PACIENTE NUMBER NOT NULL,
    DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_PRONTUARIO
        PRIMARY KEY (ID_PRONTUARIO),

    CONSTRAINT UK_PRONTUARIO_PACIENTE
        UNIQUE (ID_PACIENTE),

    CONSTRAINT FK_PRONTUARIO_PACIENTE
        FOREIGN KEY (ID_PACIENTE)
        REFERENCES PACIENTE (ID_PACIENTE)
);

ALTER TABLE ATENDIMENTO
ADD ID_PRONTUARIO NUMBER;

UPDATE ATENDIMENTO A
SET ID_PRONTUARIO = (
    SELECT P.ID_PRONTUARIO
    FROM PRONTUARIO P
    WHERE P.ID_PACIENTE = A.ID_PACIENTE
);

ALTER TABLE ATENDIMENTO
ADD CONSTRAINT FK_ATENDIMENTO_PRONTUARIO
FOREIGN KEY (ID_PRONTUARIO)
REFERENCES PRONTUARIO (ID_PRONTUARIO);

SELECT
    A.ID_ATENDIMENTO,
    A.ID_PACIENTE
FROM ATENDIMENTO A
LEFT JOIN PRONTUARIO P
    ON P.ID_PACIENTE = A.ID_PACIENTE
WHERE P.ID_PRONTUARIO IS NULL;

ALTER TABLE ATENDIMENTO
MODIFY ID_PRONTUARIO NOT NULL;