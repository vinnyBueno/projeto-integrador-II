);

CREATE TABLE registro_triagem (
    id_registro_triagem     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_atendimento          NUMBER NOT NULL,
    pressao_sistolica       NUMBER(3) NOT NULL,
    pressao_diastolica      NUMBER(3) NOT NULL,
    temperatura             NUMBER(3,1) NOT NULL,
    frequencia_cardiaca     NUMBER(3) NOT NULL,
    frequencia_respiratoria NUMBER(2) NOT NULL,
    queixas                 VARCHAR2(500) NOT NULL,
    profissional            VARCHAR2(100),
    registrado_em           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_registro_triagem PRIMARY KEY (id_registro_triagem),
    CONSTRAINT uq_registro_triagem_atend UNIQUE (id_atendimento),
    CONSTRAINT fk_registro_triagem_atend
        FOREIGN KEY (id_atendimento)
        REFERENCES atendimento (id_atendimento) ON DELETE CASCADE,
    CONSTRAINT ck_triagem_sistolica CHECK (pressao_sistolica BETWEEN 70 AND 250),
    CONSTRAINT ck_triagem_diastolica CHECK (pressao_diastolica BETWEEN 40 AND 150),
    CONSTRAINT ck_triagem_temperatura CHECK (temperatura BETWEEN 34 AND 42.5),
    CONSTRAINT ck_triagem_fc CHECK (frequencia_cardiaca BETWEEN 30 AND 220),
    CONSTRAINT ck_triagem_fr CHECK (frequencia_respiratoria BETWEEN 8 AND 60)
);

CREATE TABLE classificacao_risco (
    id_classificacao NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_atendimento   NUMBER NOT NULL,
    cor              VARCHAR2(10) NOT NULL,
    registrado_em    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_classificacao_risco PRIMARY KEY (id_classificacao),
    CONSTRAINT uq_classificacao_atend UNIQUE (id_atendimento),
    CONSTRAINT fk_classificacao_atend
        FOREIGN KEY (id_atendimento)
        REFERENCES atendimento (id_atendimento) ON DELETE CASCADE,
    CONSTRAINT ck_classificacao_cor
        CHECK (cor IN ('vermelho', 'laranja', 'amarelo', 'verde', 'azul'))
);

CREATE TABLE consulta_medica (
    id_consulta    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_atendimento NUMBER NOT NULL,
    medico_nome    VARCHAR2(100) NOT NULL,
    medico_email   VARCHAR2(100),
    anotacoes      VARCHAR2(1000),
    confirmado     NUMBER(1) DEFAULT 0 NOT NULL,
    inicio_em      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fim_em         TIMESTAMP,
    atualizado_em  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_consulta_medica PRIMARY KEY (id_consulta),
    CONSTRAINT uq_consulta_medica_atend UNIQUE (id_atendimento),
    CONSTRAINT fk_consulta_medica_atend
        FOREIGN KEY (id_atendimento)
        REFERENCES atendimento (id_atendimento) ON DELETE CASCADE,
    CONSTRAINT ck_consulta_confirmado CHECK (confirmado IN (0, 1))
);

CREATE TABLE medicacao (
    id_medicacao  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_consulta   NUMBER NOT NULL,
    nome          VARCHAR2(80) NOT NULL,
    dose          VARCHAR2(40) NOT NULL,
    via           VARCHAR2(10) NOT NULL,
    frequencia    VARCHAR2(30) NOT NULL,
    registrado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_medicacao PRIMARY KEY (id_medicacao),
    CONSTRAINT fk_medicacao_consulta
        FOREIGN KEY (id_consulta)
        REFERENCES consulta_medica (id_consulta) ON DELETE CASCADE
);