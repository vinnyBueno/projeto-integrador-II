CREATE TABLE paciente(
    id_paciente NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    cpf VARCHAR2(11) NOT NULL,
    rg VARCHAR2(11),
    genero VARCHAR(20),
    data_nascimento DATE,
    telefone VARCHAR2(15),
    telefone_emergencia VARCHAR2(15),
    email VARCHAR2(100),
    logradouro VARCHAR2(100),
    numero VARCHAR2(5),
    bairro VARCHAR2(60),
    cidade varchar2(60),
    cep varchar2(8),
    CONSTRAINT uq_paciente_cpf UNIQUE (cpf),
    CONSTRAINT uq_paciente_email UNIQUE (email)
);

CREATE TABLE FUNCAO(
    id_funcao NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome_funcao VARCHAR2(20)
);

CREATE TABLE prontuario(
    id_prontuario NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    data_criacao DATA DEFAULT SYSTEM NOT NULL,
    id_paciente NUMBER NOT NULL,
    CONSTRAINT uq_prontuario_paciente UNIQUE (id_paciente),
    CONSTRAINT fk_prontuario_paciente
        FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente)
);