CREATE TABLE consulta (
    id_servico NUMBER,
    CONSTRAINT pk_consulta PRIMARY KEY (id_servico),
    CONSTRAINT fk_consulta_servico
        FOREIGN KEY (id_servico) REFERENCES servico (id_servico)
);

CREATE TABLE triagem (
    id_servico NUMBER,
    CONSTRAINT pk_triagem PRIMARY KEY (id_servico),
    CONSTRAINT fk_triagem_servico
        FOREIGN KEY (id_servico) REFERENCES servico (id_servico)
