CREATE TABLE prontuario (
    id_prontuario NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    data_criacao  DATE DEFAULT SYSDATE NOT NULL,
    id_paciente   NUMBER NOT NULL,
    CONSTRAINT pk_prontuario PRIMARY KEY (id_prontuario),
    CONSTRAINT uq_prontuario_paciente UNIQUE (id_paciente),
    CONSTRAINT fk_prontuario_paciente
        FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente)
);


CREATE TABLE profissional (
    id_profissional       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome                  VARCHAR2(100) NOT NULL,
    registro_profissional VARCHAR2(20)  NOT NULL,
    email                 VARCHAR2(100),
    telefone              VARCHAR2(15),
    especialidade         VARCHAR2(60),
    data_contratacao      DATE,
    id_funcao             NUMBER NOT NULL,
    CONSTRAINT pk_profissional PRIMARY KEY (id_profissional),
    CONSTRAINT uq_profissional_registro UNIQUE (registro_profissional),
    CONSTRAINT uq_profissional_email UNIQUE (email),
    CONSTRAINT fk_profissional_funcao
        FOREIGN KEY (id_funcao) REFERENCES funcao (id_funcao)
);


CREATE TABLE atendimento (
    id_atendimento NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    data           DATE DEFAULT SYSDATE NOT NULL,
    hora_inicio    TIMESTAMP,
    hora_fim       TIMESTAMP,
    motivo         VARCHAR2(200),
    status         VARCHAR2(30) DEFAULT 'AGUARDANDO_TRIAGEM' NOT NULL,
    criado_em      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    atualizado_em  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    cancelado_em   TIMESTAMP,
    finalizado_em  TIMESTAMP,
    id_paciente    NUMBER NOT NULL,
    id_prontuario  NUMBER NOT NULL,
    CONSTRAINT pk_atendimento PRIMARY KEY (id_atendimento),
    CONSTRAINT ck_atendimento_status CHECK (
        status IN (
            'AGUARDANDO_TRIAGEM',
            'EM_TRIAGEM',
            'AGUARDANDO_ATENDIMENTO_MEDICO',
            'EM_ATENDIMENTO_MEDICO',
            'FINALIZADO',
            'CANCELADO'
        )
    ),
    CONSTRAINT ck_atendimento_horas
        CHECK (hora_fim IS NULL OR hora_inicio IS NULL OR hora_fim >= hora_inicio),
    CONSTRAINT fk_atend_paciente
        FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente),
    CONSTRAINT fk_atend_prontuario
        FOREIGN KEY (id_prontuario) REFERENCES prontuario (id_prontuario)
);


CREATE TABLE funcao_servico (
    id_funcao  NUMBER,
    id_servico NUMBER,
    CONSTRAINT pk_funcao_servico PRIMARY KEY (id_funcao, id_servico),
    CONSTRAINT fk_fs_funcao
        FOREIGN KEY (id_funcao) REFERENCES funcao (id_funcao),
    CONSTRAINT fk_fs_servico
        FOREIGN KEY (id_servico) REFERENCES servico (id_servico)
);


CREATE TABLE participacao (
    id_profissional NUMBER,
    id_atendimento  NUMBER,
    CONSTRAINT pk_participacao PRIMARY KEY (id_profissional, id_atendimento),
    CONSTRAINT fk_part_profissional
        FOREIGN KEY (id_profissional) REFERENCES profissional (id_profissional),
    CONSTRAINT fk_part_atendimento
        FOREIGN KEY (id_atendimento) REFERENCES atendimento (id_atendimento)
);


CREATE TABLE atendimento_servico (
    id_atendimento NUMBER,
    id_servico     NUMBER,
    CONSTRAINT pk_atendimento_servico PRIMARY KEY (id_atendimento, id_servico),
    CONSTRAINT fk_as_atendimento
